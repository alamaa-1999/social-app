  // flag like the post Composer's - there's no reducer here (plain
  // `useState` fields), and sprinkling `setIsDirty(true)` across every
  // handler is easy to miss one. Reset on mount, after a successful
  // save-to-draft, and after loading a selected draft. Covers
  // title/subtitle/metadata/coverImage only - the body's own dirtiness is
  // `bodyTouched` above, tracked separately since the markdown itself
  // isn't synchronously available to snapshot the way it used to be.
  //
  // `snapshotOf` takes explicit values rather than closing over
  // title/subtitle/metadata/coverImage directly, because the two handlers
  // below (`onClearComposer`/`onSelectDraft`) need to compute the new
  // baseline in the same synchronous call that calls `setTitle` etc. -
  // `setState` doesn't flush before the next line runs, so reading the
  // component's own state variables right after setting them would capture
  // the stale pre-update values, not what was just set.
  const snapshotOf = (v: {
    title: string
    subtitle: string
    metadata: MetadataValue
    coverImage: site.standard.document.Main['coverImage']
  }) => JSON.stringify(v)
  const snapshot = () => snapshotOf({title, subtitle, metadata, coverImage})
  const baselineRef = useRef(snapshot())
  const isDirty = bodyTouched || snapshot() !== baselineRef.current

  const hasContent =
    !!title.trim() ||
    !!subtitle.trim() ||
    !bridgeState.empty ||
    !!coverImage ||
    metadata.authors.length > 0 ||
    metadata.translators.length > 0 ||
    metadata.categories.length > 0 ||
    metadata.tags.length > 0

