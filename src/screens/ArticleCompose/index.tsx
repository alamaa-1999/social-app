  // never shrinks the layout viewport for the keyboard - only the *visual*
  // viewport does - so without this, the keyboard just covers the toolbar.
  // See `keyboardLayout.ts` for the full dependency model and why the
  // arithmetic itself lives there, unit-tested, rather than inline here.
  //
  // `GBOARD_STRIP_BUFFER` (26px) is a flat, empirically-tuned constant, not
  // a measurement - no viewport API reports Gboard's own persistent toolbar
  // strip (emoji/GIF/translate/mic, drawn above its key rows), confirmed
  // live: it left the bottom ~20-30% of this toolbar clipped under that
  // strip with no compensation. `navigator.virtualKeyboard` (the one real
  // API built for exactly this - `overlaysContent = true` unlocks
  // `boundingRect`/`geometrychange`, which would report the strip as part
  // of the same occluded region, no fitted constant needed) was tried and
  // properly re-checked with a live on-device diagnostic, not just inferred
  // from "no observed change" - `'virtualKeyboard' in navigator` is
  // genuinely `false` on this Chrome/Android build, confirmed directly.
  // This constant is Chromium/Android-specific in more ways than just that
  // absence, and every one of them is a real cost of keeping it rather than
  // a settled value: Gboard's strip can be turned off in the keyboard's own
  // settings (the buffer then becomes a 26px gap that shouldn't be there),
  // its actual height scales with display density and system font size,
  // other Android keyboards (Samsung Keyboard, SwiftKey) occlude
  // differently, and iOS has no equivalent strip *and* supports none of
  // `interactive-widget` - this whole model (this constant, and the
  // `offsetTop`-based pan tracking below and on the top toolbar) needs an
  // explicit iOS answer of its own before that platform is tested, not an
  // assumption that it carries over.
  const GBOARD_STRIP_BUFFER = 26
  const [toolbarLift, setToolbarLift] = useState(0)
