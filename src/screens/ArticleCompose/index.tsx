/**
 * The real byte length of a picked image.
 *
 * `PickerImage.size` cannot be trusted for this: it comes from
 * `getDataUriSize(uri)`, which infers a **data:** URI's size from its string
 * length. On web the picker returns a `blob:` URL of a few dozen characters,
 * so every image reports the same tiny number regardless of its actual size.
 *
 * Fetching the URI back is the one measurement that works on both platforms -
 * `blob:`, `data:` and `file:` URLs all resolve, and the bytes are already
 * local, so nothing goes over the network.
 *
 * Returns `undefined` when the size genuinely cannot be determined. Callers
 * treat that as "allow", deliberately: the PDS enforces its own ceiling, and
 * refusing an image because we failed to measure it would block a legitimate
 * upload on our own shortcoming.
 */
async function measureImageBytes(image: {
  path: string
  size?: number
}): Promise<number | undefined> {
  try {
    const response = await fetch(image.path)
    const blob = await response.blob()
    if (blob.size > 0) return blob.size
  } catch {
    // Fall through to the picker's own figure below.
  }
  return image.size && image.size > 0 ? image.size : undefined
}

/**
 * A `FocusArgs` value for "(re-)focus the editor without moving the
 * cursor," used in place of the more obvious `null`/no-argument form
 * everywhere this file needs that behavior.
 *
 * `null` looks like the right value for this - it's TipTap's own
 * documented default (`editor.commands.focus()`) - but `@tiptap/core`'s
 * `focus` command (`commands/focus.ts`) has a real, upstream footgun here:
 * `if ((view.hasFocus() && position === null) || position === false)
 * return true` short-circuits to a total no-op whenever the view *already*
 * reports having DOM focus, on the assumption that "already focused" means
 * "a caret is already visible." That assumption doesn't hold after a
 * cross-iframe click: the browser can hand DOM focus to the WebView's
 * `.ProseMirror` element without ever placing a visible Selection in it, so
 * `view.hasFocus()` is `true` while there's still no caret on screen - and
 * `.focus(null)` then does nothing at all. This isn't unique to this app:
 * TipTap's own community has hit the same "focus() does nothing" shape
 * repeatedly (e.g. `scrumpy/tiptap#389`) and the established workaround is
 * always the same - pass an explicit position instead of relying on the
 * bare/`null` form, since only the literal `position === null` trips the
 * guard.
 *
 * `0` is that explicit position, chosen instead of the community's more
 * common `'end'`/`'start'` specifically to avoid moving the cursor:
 * `resolveFocusPosition` (`helpers/resolveFocusPosition.ts`) treats *any*
 * falsy `position` - not just `null` - as "resolve to nothing," which
 * `focus.ts` then falls back to `editor.state.selection`, i.e. wherever the
 * selection already is. `0` gets that same "keep the current selection"
 * fallback while not being the literal value the guard checks for, so the
 * rest of the command runs for real: it leaves the selection untouched
 * (already "the same," so `tr.setSelection` is skipped) but unconditionally
 * calls `delayedFocus()`, which calls `view.focus()` a tick later via
 * `requestAnimationFrame` - the part that actually shows the caret.
 */
const REFOCUS_WITHOUT_MOVING_CURSOR = 0

