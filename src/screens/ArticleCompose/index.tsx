  const onSetColor = (hex: string) => {
    // Finding 20 enforcement point: the toolbar's own menu only ever offers
    // PRESET_COLORS, which already passes this trivially, but that's the
    // caller being well-behaved, not a structural guarantee. This is the
    // one place a #color.value actually gets constructed, so the allowlist
    // has to live here, not upstream - any future caller (a free-text color
    // input, say) is protected for free instead of having to remember to
    // re-check.
    if (!isAllowedColorValue(hex)) return
    editorBridge.setColor(hex)
  }

  const onSetAlign = (align: 'left' | 'center' | 'right' | 'justify') =>
    editorBridge.setTextAlign(align)

  const onInsertList = () => editorBridge.toggleBulletList()

  const onSelectParagraphStyle = (style: ParagraphStyleId) =>
    editorBridge.setParagraphStyle(style)

  const onInsertHonorific = (codepoint: number) =>
    editorBridge.insertHonorific(codepoint)

  // TipTap's `Link` mark applies over a selection, not at a bare cursor
  // position - matches TenTap's own `LinkBridge` state model exactly
  // (`canSetLink: !editor.state.selection.empty`), not a new restriction
  // this screen invents. The old placeholder-text-with-no-selection path
  // (`[link text](https://)`) doesn't have a clean equivalent under a real
  // mark-based schema, so this asks for a selection first instead - a
  // real, if minor, product behavior change worth calling out, not a
  // silent regression.
  // The popover owns the URL now (see Toolbar's `InsertLinkPopover`); this
