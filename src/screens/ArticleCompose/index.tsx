  // undoing back to the exact original text now still reads as dirty,
  // where the old snapshot comparison would have caught the match. Reset
  // explicitly wherever the body's content is replaced wholesale
  // (`onClearComposer`/`onSelectDraft`) or the draft is freshly saved.
  const [bodyTouched, setBodyTouched] = useState(false)
